//! E2.4/E2.5 — generated JS artifacts. Run by `scripts/build.sh`; never
//! edit the output.
//!
//! - `genjs`        → `game/web/js/gen/constants.js`: engine vocabulary
//!   (field registry, event table, layer ids, biomes, goods, kinds).
//! - `genjs types`  → `game/web/js/gen/types.js`: JSDoc typedefs for the
//!   WASM→JS wire contract, introspected from live payloads serialized by
//!   the engine's own `Serialize` impls — names and shapes cannot drift
//!   from the structs.

use std::collections::BTreeMap;

use calliope::constants::{self, Biome};
use calliope::entity::EntityKind;
use calliope::resources::Good;
use calliope::pack::FIELD_SPECS;
use calliope::world::{EventKind, World};
use calliope::{explain, telling};
use serde_json::Value;
use strum::IntoEnumIterator;

fn main() {
    let mode = std::env::args().nth(1).unwrap_or_default();
    if mode == "types" {
        print!("{}", gen_types());
    } else {
        print!("{}", gen_constants());
    }
}

// ---------------------------------------------------------------- E2.4

fn gen_constants() -> String {
    let mut o = String::new();
    o.push_str("// GENERATED by `cargo run --bin genjs` (scripts/build.sh) — do not edit.\n");
    o.push_str("// Engine vocabulary, straight from the Rust tables (E2.4).\n\n");

    // Layer ids exactly as the Orbital shader branches on them.
    o.push_str("export const LAYER_ID = {\n");
    for (name, id) in constants::LAYERS {
        o.push_str(&format!("  {name}: {id},\n"));
    }
    o.push_str("};\n\n");

    // The field registry: wire name, dtype, units, GPU upload flag —
    // pack order, which is also Orbital's upload order (E2.2).
    o.push_str("export const FIELDS = [\n");
    for f in FIELD_SPECS {
        o.push_str(&format!(
            "  {{ name: \"{}\", dtype: \"{}\", units: \"{}\", gpu: {} }},\n",
            f.name, f.dtype, f.units, f.gpu
        ));
    }
    o.push_str("];\n\n");

    // Event kinds with family and telling weight (E2.3's table, exported).
    o.push_str("export const EVENT_KINDS = [\n");
    for k in EventKind::iter() {
        o.push_str(&format!(
            "  {{ name: \"{}\", family: \"{}\", weight: {} }},\n",
            k.name(),
            k.family(),
            k.weight()
        ));
    }
    o.push_str("];\n\n");

    o.push_str("export const ENTITY_KINDS = ");
    let ek: Vec<String> = EntityKind::iter().map(|k| format!("\"{}\"", k.name())).collect();
    o.push_str(&format!("[{}];\n\n", ek.join(", ")));

    o.push_str("export const BIOMES = [\n");
    for b in Biome::iter() {
        o.push_str(&format!("  {{ id: {}, name: \"{}\" }},\n", b.code(), b));
    }
    o.push_str("];\n\n");

    o.push_str("export const GOODS = ");
    let goods: Vec<String> = Good::iter().map(|g| format!("\"{}\"", g.name())).collect();
    o.push_str(&format!("[{}];\n", goods.join(", ")));

    o
}

// ---------------------------------------------------------------- E2.5
//
// Structural typing of the actual wire JSON. A shape is inferred per
// sample and merged: objects union their keys (a key missing from some
// sample becomes optional), arrays merge their element shapes, and
// genuinely mixed positions become unions. Values never reach the
// output — only names and types — so wall-clock timings in the header
// don't make the generated file nondeterministic.

#[derive(Clone, PartialEq)]
enum Shape {
    Never, // no evidence (e.g. only-ever-empty arrays)
    Null,
    Bool,
    Num,
    Str,
    Arr(Box<Shape>),
    Obj(BTreeMap<String, Field>),
    Union(Vec<Shape>),
}

#[derive(Clone, PartialEq)]
struct Field {
    shape: Shape,
    required: bool,
}

fn of(v: &Value) -> Shape {
    match v {
        Value::Null => Shape::Null,
        Value::Bool(_) => Shape::Bool,
        Value::Number(_) => Shape::Num,
        Value::String(_) => Shape::Str,
        Value::Array(xs) => {
            let el = xs.iter().fold(Shape::Never, |acc, x| merge(acc, of(x)));
            Shape::Arr(Box::new(el))
        }
        Value::Object(m) => Shape::Obj(
            m.iter()
                .map(|(k, x)| (k.clone(), Field { shape: of(x), required: true }))
                .collect(),
        ),
    }
}

fn merge(a: Shape, b: Shape) -> Shape {
    match (a, b) {
        (Shape::Never, x) | (x, Shape::Never) => x,
        (x, y) if x == y => x,
        (Shape::Arr(x), Shape::Arr(y)) => Shape::Arr(Box::new(merge(*x, *y))),
        (Shape::Obj(mut x), Shape::Obj(y)) => {
            for (k, f) in x.iter_mut() {
                if !y.contains_key(k) {
                    f.required = false;
                }
            }
            for (k, fb) in y {
                match x.get_mut(&k) {
                    Some(fa) => {
                        fa.shape = merge(fa.shape.clone(), fb.shape);
                        fa.required &= fb.required;
                    }
                    None => {
                        x.insert(k, Field { shape: fb.shape, required: false });
                    }
                }
            }
            Shape::Obj(x)
        }
        (Shape::Union(mut xs), y) => {
            if !xs.contains(&y) {
                xs.push(y);
            }
            Shape::Union(xs)
        }
        (x, Shape::Union(ys)) => merge(Shape::Union(ys), x),
        (x, y) => Shape::Union(vec![x, y]),
    }
}

/// Inline type expression (used for nested positions).
fn expr(s: &Shape) -> String {
    match s {
        Shape::Never => "unknown".into(),
        Shape::Null => "null".into(),
        Shape::Bool => "boolean".into(),
        Shape::Num => "number".into(),
        Shape::Str => "string".into(),
        Shape::Arr(el) => format!("Array<{}>", expr(el)),
        Shape::Obj(m) => {
            // Record heuristic: a wide object whose values all merge into
            // one coherent shape is a string-keyed map (goods prices,
            // stage timings), not a struct — its keys vary per world.
            if m.len() >= 6 {
                let merged = m
                    .values()
                    .fold(Shape::Never, |acc, f| merge(acc, f.shape.clone()));
                if !matches!(merged, Shape::Union(_) | Shape::Never) {
                    return format!("Object<string, {}>", expr(&merged));
                }
            }
            let fields: Vec<String> = m
                .iter()
                .map(|(k, f)| {
                    format!("{}{}: {}", k, if f.required { "" } else { "?" }, expr(&f.shape))
                })
                .collect();
            format!("{{{}}}", fields.join(", "))
        }
        Shape::Union(xs) => xs.iter().map(expr).collect::<Vec<_>>().join(" | "),
    }
}

/// One named typedef block. Object roots expand one property per line.
fn typedef(name: &str, doc: &str, s: &Shape) -> String {
    let mut o = String::new();
    o.push_str("/**\n");
    o.push_str(&format!(" * {doc}\n"));
    match s {
        Shape::Obj(m) => {
            o.push_str(&format!(" * @typedef {{Object}} {name}\n"));
            for (k, f) in m {
                if f.required {
                    o.push_str(&format!(" * @property {{{}}} {}\n", expr(&f.shape), k));
                } else {
                    o.push_str(&format!(" * @property {{{}}} [{}]\n", expr(&f.shape), k));
                }
            }
        }
        _ => o.push_str(&format!(" * @typedef {{{}}} {}\n", expr(s), name)),
    }
    o.push_str(" */\n\n");
    o
}

fn header_value(pack: &[u8]) -> Value {
    let hlen = u32::from_le_bytes(pack[0..4].try_into().unwrap()) as usize;
    serde_json::from_slice(&pack[4..4 + hlen]).expect("pack header is JSON")
}

fn gen_types() -> String {
    // A real world, ticked far enough that every wire surface has content.
    let mut w = World::generate(12345, 256);
    // E3.1 — the client's view is pack header + bootstrap merged; typedefs
    // describe that merged object, exactly what net.js hands the app.
    let mut header = header_value(&w.pack());
    for (k, v) in w.bootstrap().as_object().unwrap() {
        header[k.as_str()] = v.clone();
    }
    let header = header;

    // Two tick samples: an early one (rarely founds a colony) and a long
    // one — merging makes conditionally-present keys (routes) optional.
    let t1: Value = serde_json::from_str(&w.tick_json(1)).unwrap();
    let t2: Value = serde_json::from_str(&w.tick_json(239)).unwrap();
    let tick = merge(of(&t1), of(&t2));

    let events = of(&serde_json::to_value(&w.chronicle.events).unwrap());
    let entities = of(&serde_json::to_value(&w.chronicle.registry.items).unwrap());
    let stories = of(&serde_json::to_value(telling::sift(&w.chronicle.events, &w.chronicle.registry)).unwrap());
    let artifacts = of(&serde_json::to_value(&w.chronicle.artifacts).unwrap());

    // Explain ledgers for both kinds, merged into one contract.
    let sid = header["settlements"][0]["id"].to_string();
    let e1: Value = serde_json::from_str(&explain::explain(&w, "settlement", &sid)).unwrap();
    let good = Good::iter().next().unwrap().name().to_string();
    let e2: Value = serde_json::from_str(&explain::explain(&w, "good", &good)).unwrap();
    let explain_shape = merge(of(&e1), of(&e2));

    let el = |s: &Shape| -> Shape {
        match s {
            Shape::Arr(el) => (**el).clone(),
            other => other.clone(),
        }
    };

    let mut o = String::new();
    o.push_str("// GENERATED by `cargo run --bin genjs -- types` (scripts/build.sh) — do not edit.\n");
    o.push_str("// The WASM→JS wire contract (E2.5), introspected from live payloads\n");
    o.push_str("// serialized by the engine's own Serialize impls. `kind` fields are\n");
    o.push_str("// numeric on the wire; net.js decodes them to names at the edge.\n\n");
    o.push_str(&typedef(
        "WorldHeader",
        "The pack header: meta + entity lists riding ahead of the field arrays.",
        &of(&header),
    ));
    o.push_str(&typedef(
        "Tick",
        "Result of advancing the simulation; `routes` only when a colony was founded.",
        &tick,
    ));
    o.push_str(&typedef("ChronicleEvent", "One chronicle entry (wire form).", &el(&events)));
    o.push_str(&typedef("Entity", "One registry entity (wire form).", &el(&entities)));
    o.push_str(&typedef("Story", "One sifted microstory.", &el(&stories)));
    o.push_str(&typedef("Artifact", "One relic with its provenance.", &el(&artifacts)));
    o.push_str(&typedef(
        "ExplainLedger",
        "Term ledger behind a derived quantity, or null when the engine has nothing to say.",
        &explain_shape,
    ));
    o.push_str("export {};\n");
    o
}
